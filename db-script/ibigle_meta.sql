ALTER TABLE DIMENSION_DEFINITION_T COMMENT = '维度定义表（动态扩展）';

CREATE TABLE AUTHORIZATION_POLICY_T (
  POLICY_ID BIGINT NOT NULL AUTO_INCREMENT COMMENT '策略Id',
  PRINCIPAL_TYPE varchar(20) NOT NULL COMMENT '对象类型，USER->用户, ROLE->角色, GROUP->用户组',
  PRINCIPAL_ID BIGINT NOT NULL COMMENT '对象主键,用户ID/角色ID/组ID',
  PERMISSION_CODE varchar(64) NOT NULL COMMENT '权限编码',
  DIMENSION_FILTERS json DEFAULT NULL COMMENT '数据维度过滤条件json格式，如{"tenant":["A"],"dept":[100]}',
  POLICY_EFFECT varchar(10) DEFAULT 'ALLOW' COMMENT '策略方向，ALLOW->允许 DENY->拒绝，DENY优先级高于ALLOW',
  VALID_FROM VARCHAR(20) NULL COMMENT '生效日期，格式：YYYYMMDD->20251110',
  VALID_TO VARCHAR(20) NULL COMMENT '失效日期，格式：YYYYMMDD->20251110',
  TENANT_ID BIGINT NOT NULL COMMENT '租户Id',
  CREATED_BY VARCHAR(128) NULL COMMENT '创建人',
  CREATED_DT DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  UPDATED_BY VARCHAR(128) NULL COMMENT '最后更新人',
  UPDATED_DT DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '最后更新时间',
  PRIMARY KEY (POLICY_ID),
  KEY IDX_PRINCIPAL (PRINCIPAL_TYPE, PRINCIPAL_ID),
  KEY IDX_PERMISSION_CODE (PERMISSION_CODE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

ALTER TABLE AUTHORIZATION_POLICY_T COMMENT = '授权策略表';

